        public static Item? SearchForBossItem(string bossName, string dropName)
        {
            switch (bossName)
            {
                case BossNames.Cox:
                    return CheckCoxItems(dropName);
                case BossNames.Tob:
                    return CheckTobItems(dropName);
                case BossNames.Toa:
                    return CheckToaItems(dropName);
                case BossNames.CG:
                    return CheckCGItems(dropName);
                case BossNames.Global:
                    return CheckAllItems(dropName);
                default:
                    return null;
            }
        }

        private static Item? CheckCoxItems(string dropName) => CoxItems.FirstOrDefault(x => dropName.Equals(x.Name, StringComparison.InvariantCultureIgnoreCase)
                                || x.Aliases.Contains(dropName, StringComparer.InvariantCultureIgnoreCase));
        private static Item? CheckTobItems(string dropName) => TobItems.FirstOrDefault(x => dropName.Equals(x.Name, StringComparison.InvariantCultureIgnoreCase)
                                || x.Aliases.Contains(dropName, StringComparer.InvariantCultureIgnoreCase));
        private static Item? CheckToaItems(string dropName) => ToaItems.FirstOrDefault(x => dropName.Equals(x.Name, StringComparison.InvariantCultureIgnoreCase)
                                || x.Aliases.Contains(dropName, StringComparer.InvariantCultureIgnoreCase));
        private static Item? CheckCGItems(string dropName) => CGItems.FirstOrDefault(x => dropName.Equals(x.Name, StringComparison.InvariantCultureIgnoreCase)
                                || x.Aliases.Contains(dropName, StringComparer.InvariantCultureIgnoreCase));

        private static Item? CheckAllItems(string dropName)
        {
            Item? item;

            item = CheckCoxItems(dropName);
            if (item != null)
            {
                return item;
            }
            item = CheckTobItems(dropName);
            if (item != null)
            {
                return item;
            }
            item = CheckToaItems(dropName);
            if (item != null)
            {
                return item;
            }
            item = CheckCGItems(dropName);
            if(item != null)
            {
                return item;
            }

            return null;
        }
